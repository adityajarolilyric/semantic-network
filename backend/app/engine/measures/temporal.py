"""Calendar-aware SQL windows; no row data leaves ClickHouse."""

from contextlib import contextmanager
from copy import deepcopy

from sqlglot import exp, parse_one

from ...formula_language.temporal import window_spec
from ...warehouse.sql import quote_identifier as q
from ..sql.contracts import Check
from .contracts import COMPLETE, VALUE


def period_expression(context, alias="p"):
    column = f"{alias}.{q(context['orderColumnId'])}"
    unit = context["periodUnit"]
    return (
        f"toInt64OrNull(toString({column}))"
        if unit == "index"
        else f"dateDiff('{unit}',toDate('1970-01-05'),{column})"
    )


def partition_columns(context):
    return list(
        dict.fromkeys(
            [
                *context["partitionColumnIds"],
                *([context["resetColumnId"]] if context.get("resetColumnId") else []),
            ]
        )
    )


def boundary(value, start):
    if value is None:
        return "UNBOUNDED PRECEDING" if start else "UNBOUNDED FOLLOWING"
    if value == 0:
        return "CURRENT ROW"
    return f"{abs(value)} {'PRECEDING' if value < 0 else 'FOLLOWING'}"


@contextmanager
def full_temporal_input(compiler):
    compiler.temporal_input_depth += 1
    try:
        yield
    finally:
        compiler.temporal_input_depth -= 1


class TemporalMeasureCompiler:
    def __init__(self, compiler):
        self.compiler = compiler

    def compile(self, node, measure, target):
        c = self.compiler
        context = measure["definition"]["temporal"]
        argument = deepcopy(measure)
        argument["definition"]["formula"]["expression"] = node["arguments"][0]
        # Evaluate the argument over the complete series, including unchanged stored
        # contributors during an edit. Never overlay this synthetic argument as its owner.
        with full_temporal_input(c):
            source = c.formula_compiler.compile_calculated_measure(argument, target)
        population = c.temporal_population(measure, target)
        order = period_expression(context)
        partitions = partition_columns(context)
        grouping = [f"p.{q(k)}" for k in partitions] + [order]
        c.assertions.append(
            Check(
                "temporal_order_conflict",
                f"SELECT {', '.join(grouping)},count() FROM ({population}) p GROUP BY {', '.join(grouping)} HAVING count()>1 OR isNull({order}) LIMIT 20",
            )
        )
        reducer, start, end = window_spec(node)
        specification = (
            (
                "PARTITION BY " + ", ".join(f"p.{q(k)}" for k in partitions) + " "
                if partitions
                else ""
            )
            + f"ORDER BY {order} RANGE BETWEEN {boundary(start, True)} AND {boundary(end, False)}"
        )

        # Parse the structural window once; arguments and identifiers are generated by
        # the semantic compiler. The operation is selected exclusively from a whitelist.
        def window(expression):
            return parse_one(f"{expression} OVER ({specification})", read="clickhouse")

        value = f"a.{q(VALUE)}"
        count = window(f"count({value})")
        complete = (
            f"a.{q(COMPLETE)}"
            if source in c.coverage_nodes or source in c.mixed_nodes
            else "1"
        )
        known = window(f"min({complete})")
        mixed = window(f"max({complete})")
        result = window(f"{reducer}({value})")
        empty = (
            exp.Null()
            if measure["definition"]["aggregation"]["allNullResult"] == "null"
            else exp.convert(0)
        )
        # A missing/NULL period never becomes a fabricated zero observation. COUNT
        # remains zero on an empty frame; other reducers obey all-null result policy.
        result = exp.Anonymous(
            this="if",
            expressions=[
                exp.EQ(this=count.copy(), expression=exp.convert(0)),
                exp.convert(0) if reducer == "count" else empty,
                result,
            ],
        )
        minimum = max(
            context.get("minimumPeriods", 1), 2 if reducer == "stddevSamp" else 1
        )
        if minimum > 1:
            result = exp.Anonymous(
                this="if",
                expressions=[
                    exp.LT(this=count.copy(), expression=exp.convert(minimum)),
                    exp.Null(),
                    result,
                ],
            )
        if measure["definition"]["aggregation"]["nullInputPolicy"] == "propagate":
            nulls = window(f"countIf(isNull({value}))")
            result = exp.Anonymous(
                this="if",
                expressions=[
                    exp.GT(this=nulls, expression=exp.convert(0)),
                    exp.Null(),
                    result,
                ],
            )
        sql_value = result.sql(dialect="clickhouse")
        frame_size = window("count() ").sql(dialect="clickhouse")
        flag = f"if(({frame_size})=0,toUInt8(1),if(({mixed.sql(dialect='clickhouse')})=2,toUInt8(2),if(({known.sql(dialect='clickhouse')})=0,toUInt8(0),toUInt8(1))))"
        keys = ", ".join(f"p.{q(k)} AS {q(k)}" for k in c.keys(target))
        evaluated = c.cte(
            f"SELECT {keys},if(({flag})=1,{sql_value},NULL) AS {q(VALUE)}, {flag} AS {q(COMPLETE)} FROM ({population}) p LEFT JOIN {q(source)} a ON {c.join_keys('p', 'a', target)}"
        )
        c.coverage_nodes[evaluated] = True
        c.mixed_nodes.add(evaluated)
        return evaluated
